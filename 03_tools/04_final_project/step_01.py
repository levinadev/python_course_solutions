r"""
Урок "Итоговый проект", шаг 1
https://stepik.org/lesson/2493474/step/1

Анализ текста
Условие
Напишите программу, которая анализирует введённый текст и выводит статистику по нему.
Что должна делать программа.
- Считывать строку текста.
- Выводить количество слов в тексте.
- Выводить самое длинное слово.
- Выводить количество уникальных слов (с помощью множества).
- Проверять, все ли слова длиннее 3 символов, выводить `True` или `False`.
Требования
- Используйте `try-except` для обработки пустого ввода. Если в строке нет ни одного слова, выведите
`Пустой ввод`.
- Используйте `max()` с параметром `key=len` для поиска самого длинного слова.
- Используйте множества для подсчёта уникальных слов.
- Используйте `all()` для проверки длины всех слов.
Ввод
На вход подаётся строка с текстом, например `яблоко банан апельсин груша апельсин`.
Вывод
Четыре строки.
- Количество слов.
- Самое длинное слово.
- Количество уникальных слов.
- Все ли слова длиннее 3 символов (`True`/`False`).
🔑 Подсказка
- Слова получите методом `.split()`, их количество равно длине получившегося списка.
- Количество уникальных слов равно длине множества `set(words)`.
- В `all()` передайте генераторное выражение, которое для каждого слова проверяет `len(w) > 3`.
- Весь разбор текста и вывод поместите в блок `try`, а в `except` выведите `Пустой ввод`.
"""

text = input()
try:
    words = text.split()
    longest = max(words, key=len)
    print(len(words))
    print(longest)
    print(len(set(words)))
    print(all(len(w) > 3 for w in words))
except ValueError:
    print("Пустой ввод")
