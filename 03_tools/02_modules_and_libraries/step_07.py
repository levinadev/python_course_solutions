r"""
Урок "Модули и библиотеки", шаг 7
https://stepik.org/lesson/2493468/step/7

Напишите программу, которая считывает радиус круга (целое число) и выводит его площадь, округлённую
функцией `round()` до двух знаков после точки.
Площадь считается по формуле `S = π * r²`. Используйте константу `math.pi`.
🔑 Подсказка
Квадрат радиуса записывается как `r ** 2`, площадь как `math.pi * r ** 2`. Чтобы оставить два знака
после точки, передайте площадь в `round()` вторым аргументом 2, `round(s, 2)`.
"""

import math

r = int(input())
print(round(math.pi * r ** 2, 2))
