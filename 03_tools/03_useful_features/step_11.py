r"""
Урок "Полезные возможности Python", шаг 11
https://stepik.org/lesson/2493471/step/11

Считайте натуральное число `n`. Создайте словарь, где ключами служат числа от 1 до `n`, а значениями
их квадраты. Используйте генератор словаря. Выведите словарь.
🔑 Подсказка
Генератор словаря похож на генератор списка, только он в фигурных скобках и начинается с пары `ключ:
значение`.
"""

n = int(input())
print({i: i ** 2 for i in range(1, n + 1)})
