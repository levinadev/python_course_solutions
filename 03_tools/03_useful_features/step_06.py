r"""
Урок "Полезные возможности Python", шаг 6
https://stepik.org/lesson/2493471/step/6

Создайте lambda-функцию, которая принимает число и возвращает его куб (`x ** 3`).
Программа считывает длину ребра кубика в сантиметрах (целое число). С помощью lambda-функции
вычислите и выведите объём кубика.
🔑 Подсказка
Lambda записывается как `cube = lambda x: x ** 3` и вызывается как обычная функция, `cube(5)`. Длину
ребра переведите через `int()`.
"""

cube = lambda x: x ** 3
print(cube(int(input())))
