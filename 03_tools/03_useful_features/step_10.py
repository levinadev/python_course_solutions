r"""
Урок "Полезные возможности Python", шаг 10
https://stepik.org/lesson/2493471/step/10

Считайте натуральное число `n`. Создайте список квадратов чисел от 1 до `n` с помощью генератора
списков и выведите его.
🔑 Подсказка
Генератор списка записывается в квадратных скобках, сначала выражение, потом цикл. Чтобы n вошло в
список, верхняя граница `range()` должна быть `n + 1`.
"""

n = int(input())
print([i ** 2 for i in range(1, n + 1)])
