r"""
Урок "Полезные возможности Python", шаг 4
https://stepik.org/lesson/2493471/step/4

Даны три строки, школьное расписание на день. В них названия предметов, время начала уроков и номера
кабинетов (через пробел, в каждой строке одинаковое количество; название предмета из одного слова).
Используя `zip()`, выведите для каждого урока строку `Урок: {предмет}, Начало: {время}, Кабинет:
{кабинет}`.
🔑 Подсказка
`zip()` принимает и три списка сразу, тогда в цикле будет три переменные, `for subject, time, room
in zip(subjects, times, rooms)`.
"""

subjects = input().split()
times = input().split()
rooms = input().split()
for subject, time, room in zip(subjects, times, rooms):
    print(f"Урок: {subject}, Начало: {time}, Кабинет: {room}")
