r"""
Урок "Полезные возможности Python", шаг 7
https://stepik.org/lesson/2493471/step/7

Программа считывает длины сторон нескольких квадратных плиток в сантиметрах, целые числа через
пробел.
Используя `map()` и lambda, вычислите площадь каждой плитки (сторона в квадрате) и выведите
результат в виде списка.
🔑 Подсказка
`map()` применяет функцию к каждому элементу. Первым аргументом передайте lambda, вторым список,
например `map(lambda a: a ** 2, sides)`. Результат превратите в список через `list()`.
"""

sides = [int(x) for x in input().split()]
print(list(map(lambda a: a ** 2, sides)))
