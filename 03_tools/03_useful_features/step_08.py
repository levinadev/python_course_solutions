r"""
Урок "Полезные возможности Python", шаг 8
https://stepik.org/lesson/2493471/step/8

Программа считывает температуру воздуха за несколько дней, целые числа через пробел.
Используя `filter()` и lambda, оставьте только тёплые дни с температурой выше нуля и выведите их
температуры в виде списка.
🔑 Подсказка
`filter()` оставляет элементы, для которых функция вернула `True`. Тёплый день проверяет условие `t
> 0`, а результат оберните в `list()`.
"""

temps = [int(x) for x in input().split()]
print(list(filter(lambda t: t > 0, temps)))
