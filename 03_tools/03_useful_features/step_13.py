r"""
Урок "Полезные возможности Python", шаг 13
https://stepik.org/lesson/2493471/step/13

На вход подаётся строка, в ней целые числа через пробел (нуля среди них нет). Используя `any()` и
`all()`, выполните две проверки.
- Проверьте, есть ли в списке хотя бы одно отрицательное число (`any`).
- Проверьте, все ли числа положительные (`all`).
Выведите результаты в формате `Есть отрицательное: {True/False}` и `Все положительные:
{True/False}`, каждый на отдельной строке.
🔑 Подсказка
В `any()` и `all()` передайте генераторное выражение, например `any(x < 0 for x in numbers)`.
Результат подставьте в f-строку.
"""

numbers = [int(x) for x in input().split()]
print(f"Есть отрицательное: {any(x < 0 for x in numbers)}")
print(f"Все положительные: {all(x > 0 for x in numbers)}")
