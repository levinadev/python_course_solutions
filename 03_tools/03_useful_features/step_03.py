r"""
Урок "Полезные возможности Python", шаг 3
https://stepik.org/lesson/2493471/step/3

Даны две строки. В первой буквы через пробел, во второй числа через пробел (их количество может
отличаться).
Используя `zip()`, выведите пары в формате `{letter}: {number}`, каждую на отдельной строке.
🔑 Подсказка
`zip()` останавливается на самом коротком списке, поэтому лишние элементы длинного списка просто не
попадут в вывод.
"""

letters = input().split()
numbers = input().split()
for letter, number in zip(letters, numbers):
    print(f"{letter}: {number}")
