r"""
Урок "Исключения", шаг 3
https://stepik.org/lesson/2493466/step/3

Напишите программу, которая считывает два числа и выводит их частное.
Если пользователь вводит вторым числом 0, программа должна вывести `"Деление на ноль!"` вместо
ошибки.
🔑 Подсказка
Деление поместите в блок `try`, а ошибку деления на ноль ловите через `except ZeroDivisionError`.
"""

a = int(input())
b = int(input())
try:
    print(a / b)
except ZeroDivisionError:
    print("Деление на ноль!")
