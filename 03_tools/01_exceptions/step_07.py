r"""
Урок "Исключения", шаг 7
https://stepik.org/lesson/2493466/step/7

Напишите программу, которая считывает возраст пользователя и выводит `"Доступ разрешён"`, если
возраст 18 или больше.
- Если введено не число, вывести `"Ошибка ввода"`.
- Если возраст меньше 18, вывести `"Доступ запрещён"`.
🔑 Подсказка
В `try` переведите ввод в число и уже там проверьте возраст через `if` и `else`. В `except
ValueError` выведите "Ошибка ввода".
"""

try:
    age = int(input())
    if age >= 18:
        print("Доступ разрешён")
    else:
        print("Доступ запрещён")
except ValueError:
    print("Ошибка ввода")
