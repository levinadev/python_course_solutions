r"""
Урок "Исключения", шаг 8
https://stepik.org/lesson/2493466/step/8

Кондитер раскладывает конфеты по коробкам поровну. Напишите программу, которая считывает два целых
числа, количество конфет и количество коробок, и выводит, сколько конфет попадёт в каждую коробку.
Для деления используйте `//`.
- Если деление прошло без ошибки, после этого числа выведите `"Конфеты разложены"`.
- Если количество коробок равно 0, выведите `"Коробок нет"`.
- В любом случае последней строкой выведите `"Работа завершена"`.
🔑 Подсказка
Деление поместите в `try`, а ошибку деления на ноль ловите через `except ZeroDivisionError`. Блок
`else` выполняется, только если ошибки не было, а `finally` выполняется всегда.
"""

candies = int(input())
boxes = int(input())
try:
    print(candies // boxes)
except ZeroDivisionError:
    print("Коробок нет")
else:
    print("Конфеты разложены")
finally:
    print("Работа завершена")
