r"""
Урок "Итоговый проект", шаг 1
https://stepik.org/lesson/2493482/step/1

Система управления товарами
Условие
Напишите программу, которая работает с каталогом товаров.
Что должна делать программа.
- Создавать товары с названием и ценой (класс `Product`).
- Добавлять товары в корзину (класс `Cart`).
- Выводить общую стоимость всех товаров в корзине.
- Выводить информацию о каждом товаре в корзине.
Требования
- Создайте класс `Product`, в нём два метода.
- Конструктор `__init__(self, name, price)`.
- Метод `__str__(self)`, который возвращает строку в формате `"Товар: {name}, Цена: {price} руб."`.
- Создайте класс `Cart`, в нём четыре метода.
- Конструктор `__init__(self)`, который создаёт пустой список `self.items` для хранения товаров.
- Метод `add_product(self, product)`, который добавляет товар в корзину.
- Метод `get_total(self)`, который возвращает общую стоимость всех товаров.
- Метод `show_items(self)`, который выводит информацию о каждом товаре в корзине (каждый на
отдельной строке).
Ввод
В первой строке количество товаров `n`, далее `n` строк вида `название цена` (название из одного
слова, цена целым числом). Создайте товары и добавьте их в корзину в этом порядке.
Вывод
Сначала выводится информация о каждом товаре в корзине, затем общая стоимость.
- Информация о каждом товаре (каждый на отдельной строке).
- Общая стоимость в формате `"Общая стоимость: {total} руб."`.
🔑 Подсказка
- `__str__` возвращает строку через `return`, а не выводит её через `print`.
- `add_product` добавляет товар в `self.items` методом `append()`, а `get_total` проходит по
`self.items` циклом и складывает `price` каждого товара.
- В `show_items` достаточно `print(item)`, Python сам вызовет `__str__`.
- Каждую строку ввода разделите методом `.split()` на название и цену, цену переведите в `int()`,
создайте `Product` и добавьте его в корзину.
- В конце вызовите `show_items()` и выведите результат `get_total()`.
"""

class Product:
    def __init__(self, name, price):
        self.name = name
        self.price = price

    def __str__(self):
        return f"Товар: {self.name}, Цена: {self.price} руб."


class Cart:
    def __init__(self):
        self.items = []

    def add_product(self, product):
        self.items.append(product)

    def get_total(self):
        total = 0
        for item in self.items:
            total += item.price
        return total

    def show_items(self):
        for item in self.items:
            print(item)


cart = Cart()
for _ in range(int(input())):
    name, price = input().split()
    cart.add_product(Product(name, int(price)))
cart.show_items()
print(f"Общая стоимость: {cart.get_total()} руб.")
