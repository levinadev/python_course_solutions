r"""
Урок "Наследование", шаг 4
https://stepik.org/lesson/2493479/step/4

Создайте класс `Animal` с методом `speak()`, который выводит `Животное издаёт звук`. Создайте класс
`Cat`, который наследует от `Animal` и переопределяет `speak()` так, чтобы он выводил `Мяу!`.
На вход подаётся строка, в ней названия классов через пробел (`Cat` или `Animal`). Для каждого
названия создайте объект этого класса и вызовите у него метод `speak()`.
🔑 Подсказка
В цикле по названиям сравнивайте название со строкой `"Cat"` и создавайте `Cat()` или `Animal()`, а
затем вызывайте у объекта `speak()`.
"""

class Animal:
    def speak(self):
        print("Животное издаёт звук")


class Cat(Animal):
    def speak(self):
        print("Мяу!")


classes = {"Cat": Cat, "Animal": Animal}
for name in input().split():
    classes[name]().speak()
