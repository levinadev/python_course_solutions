r"""
Урок "Наследование", шаг 6
https://stepik.org/lesson/2493479/step/6

Создайте класс `Vehicle` с методом `move()`, который выводит `Транспортное средство движется`.
Создайте класс `Car`, который наследует от `Vehicle` и переопределяет `move()`. Новый метод сначала
вызывает родительский метод через `super().move()`, затем выводит `Машина едет по дороге`.
На вход подаётся строка, в ней названия классов через пробел (`Car` или `Vehicle`). Для каждого
названия создайте объект этого класса и вызовите у него метод `move()`.
🔑 Подсказка
В `move()` класса `Car` сначала вызовите `super().move()`, потом свой `print()`. Объект нужного
класса выбирайте в цикле через `if`, по названию из ввода.
"""

class Vehicle:
    def move(self):
        print("Транспортное средство движется")


class Car(Vehicle):
    def move(self):
        super().move()
        print("Машина едет по дороге")


classes = {"Car": Car, "Vehicle": Vehicle}
for name in input().split():
    classes[name]().move()
