r"""
Урок "Инкапсуляция", шаг 6
https://stepik.org/lesson/2493478/step/6

Создайте класс `User` с приватным атрибутом `__age`. Конструктор принимает возраст и сохраняет его.
Геттер возвращает возраст. Сеттер принимает новое значение. Если оно меньше 0, выводит `Возраст не
может быть отрицательным!`, иначе сохраняет значение.
Считайте три целых числа (каждое с новой строки), начальный возраст и два новых значения. Создайте
объект с начальным возрастом, затем по очереди присвойте возрасту оба новых значения. Выведите
итоговый возраст.
🔑 Подсказка
Геттер и сеттер называются одинаково, `age`, а над сеттером пишется `@age.setter`. Присваивание
`user.age = 5` вызывает сеттер, поэтому проверка на отрицательное значение сработает сама.
"""

class User:
    def __init__(self, age):
        self.__age = age

    @property
    def age(self):
        return self.__age

    @age.setter
    def age(self, value):
        if value < 0:
            print("Возраст не может быть отрицательным!")
        else:
            self.__age = value


user = User(int(input()))
user.age = int(input())
user.age = int(input())
print(user.age)
