r"""
Урок "Введение в функции", шаг 7
https://stepik.org/lesson/2493451/step/7

Напишите функцию `max_of_two(a, b)`, которая принимает два числа и возвращает большее из них.
Считайте два числа с клавиатуры (через `input()`), вызовите функцию и выведите результат.
🔑 Подсказка
Внутри функции сравните числа через `if a > b` и верните большее через `return`. Оба числа
переведите через `int()`.
"""

def max_of_two(a, b):
    if a > b:
        return a
    return b


print(max_of_two(int(input()), int(input())))
