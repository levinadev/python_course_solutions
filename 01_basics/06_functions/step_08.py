r"""
Урок "Введение в функции", шаг 8
https://stepik.org/lesson/2493451/step/8

Напишите функцию `say_hello(name="гость")`, которая выводит `"Привет, {name}!"`.
Если имя не передано, используется `"гость"`.
Сначала вызовите функцию без аргумента, затем считайте имя с клавиатуры (через `input()`) и вызовите
с ним.
🔑 Подсказка
Значение по умолчанию пишется прямо в скобках, `def say_hello(name="гость"):`. Первый вызов
`say_hello()` без аргумента выведет "Привет, гость!", второй получит имя из `input()`.
"""

def say_hello(name="гость"):
    print(f"Привет, {name}!")


say_hello()
say_hello(input())
