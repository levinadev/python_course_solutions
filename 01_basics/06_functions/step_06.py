r"""
Урок "Введение в функции", шаг 6
https://stepik.org/lesson/2493451/step/6

Напишите функцию `square(n)`, которая принимает число и возвращает его квадрат.
Считайте число с клавиатуры (через `input()`), вызовите функцию и выведите результат.
🔑 Подсказка
Функция не выводит, а возвращает результат через `return n * n`. Выводит его `print()` снаружи,
например `print(square(x))`. Число переведите через `int()`.
"""

def square(n):
    return n * n


print(square(int(input())))
