r"""
Урок "Введение в функции", шаг 5
https://stepik.org/lesson/2493451/step/5

Напишите функцию `greet_user(name)`, которая принимает имя и выводит строку `"Привет, {имя}!"`.
Вызовите функцию, передав имя, которое считывается с клавиатуры (через `input()`).
🔑 Подсказка
Внутри функции подставьте параметр в f-строку `f"Привет, {name}!"`. Вызвать функцию можно сразу с
вводом, `greet_user(input())`.
"""

def greet_user(name):
    print(f"Привет, {name}!")


greet_user(input())
