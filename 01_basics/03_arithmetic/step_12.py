r"""
Урок "Арифметические операции", шаг 12
https://stepik.org/lesson/2493448/step/12

Напишите программу, которая считывает целое число `n`, а затем с помощью сокращённого присваивания
(`*=`) умножает его на `3` и выводит результат.
🔑 Подсказка
Запись `n *= 3` делает то же, что `n = n * 3`. После неё выведите `n`.
"""

n = int(input())
n *= 3
print(n)
