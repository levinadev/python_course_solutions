r"""
Урок "Итоговый проект", шаг 1
https://stepik.org/lesson/2493453/step/1

Калькулятор целых чисел
Условие
Напишите программу, калькулятор для целых чисел, который работает так.
- Запрашивает у пользователя первое целое число.
- Запрашивает у пользователя оператор (`+`, `-`, `*`, `/`).
- Запрашивает у пользователя второе целое число.
- Выполняет операцию и выводит результат.
Обработка ошибок
- При делении на ноль программа должна вывести `"Деление на ноль!"`.
- Если введён неизвестный оператор, вывести `"Неизвестный оператор"`.
Ввод
На вход подаются три строки.
- Первое целое число.
- Оператор (`+`, `-`, `*`, `/`).
- Второе целое число.
Вывод
Результат в формате `число1 оператор число2 = результат`.
Деление обычное, как у оператора `/`, поэтому результат дробный, например `7 / 2 = 3.5` и `10 / 5 =
2.0`.
При ошибке выводится сообщение `"Деление на ноль!"` или `"Неизвестный оператор"`.
🔑 Подсказка
- Числа считайте через `int(input())`, а оператор обычным `input()`, он и так строка.
- Оператор проверяйте цепочкой `if`, `elif`, `else`. В каждой ветке сразу выводите результат
f-строкой, например `f"{a} + {b} = {a + b}"`.
- В ветке деления сначала проверьте, что второе число не равно нулю.
"""

a = int(input())
op = input()
b = int(input())
if op == "+":
    print(f"{a} + {b} = {a + b}")
elif op == "-":
    print(f"{a} - {b} = {a - b}")
elif op == "*":
    print(f"{a} * {b} = {a * b}")
elif op == "/":
    if b == 0:
        print("Деление на ноль!")
    else:
        print(f"{a} / {b} = {a / b}")
else:
    print("Неизвестный оператор")
