r"""
Урок "Условный оператор", шаг 6
https://stepik.org/lesson/2493449/step/6

Напишите программу, которая считывает количество баллов (целое число от 0 до 100).
Выведите оценку по шкале.
- `"Отлично"` за 90-100 баллов
- `"Хорошо"` за 70-89 баллов
- `"Удовлетворительно"` за 50-69 баллов
- `"Неудовлетворительно"` за 0-49 баллов
🔑 Подсказка
Проверяйте баллы сверху вниз цепочкой `if`, `elif`, `else`. Если первым идёт `score >= 90`, то
следующему условию хватит `score >= 70`, ведь 90 и выше уже отсеяны.
"""

score = int(input())
if score >= 90:
    print("Отлично")
elif score >= 70:
    print("Хорошо")
elif score >= 50:
    print("Удовлетворительно")
else:
    print("Неудовлетворительно")
