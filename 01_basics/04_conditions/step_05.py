r"""
Урок "Условный оператор", шаг 5
https://stepik.org/lesson/2493449/step/5

Напишите программу, которая считывает возраст человека.
Если возраст 18 или больше, выведите `"Можно голосовать"`, иначе `"Нельзя голосовать"`.
🔑 Подсказка
Условие "18 или больше" записывается как `age >= 18`.
"""

age = int(input())
if age >= 18:
    print("Можно голосовать")
else:
    print("Нельзя голосовать")
