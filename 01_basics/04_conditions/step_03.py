r"""
Урок "Условный оператор", шаг 3
https://stepik.org/lesson/2493449/step/3

Напишите программу, которая считывает целое число.
Используя условный оператор `if-else`, выведите одно из двух слов.
- `"Чётное"`, если число делится на 2 без остатка;
- `"Нечётное"` в противном случае.
🔑 Подсказка
Чётность проверяйте условием `n % 2 == 0`. В ветке `if` выведите "Чётное", в ветке `else`
"Нечётное".
"""

n = int(input())
if n % 2 == 0:
    print("Чётное")
else:
    print("Нечётное")
