r"""
Урок "Условный оператор", шаг 4
https://stepik.org/lesson/2493449/step/4

Даны два целых числа. Выведите большее из них.
Если числа равны, выведите `"Равны"`.
🔑 Подсказка
Сначала проверьте равенство `a == b`, затем через `elif` сравните `a > b`, а в `else` останется
случай, когда больше второе число.
"""

a = int(input())
b = int(input())
if a == b:
    print("Равны")
elif a > b:
    print(a)
else:
    print(b)
