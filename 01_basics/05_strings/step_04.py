r"""
Урок "Строки и методы строк", шаг 4
https://stepik.org/lesson/2493450/step/4

Напишите программу, которая считывает строку и два целых числа, начальный и конечный индексы.
Выведите подстроку от начального индекса (включая) до конечного (не включая).
Гарантируется, что индексы корректны.
🔑 Подсказка
Подстроку даёт срез `s[start:end]`, он как раз не включает символ с индексом `end`. Оба индекса
переведите в числа через `int()`.
"""

s = input()
start = int(input())
end = int(input())
print(s[start:end])
