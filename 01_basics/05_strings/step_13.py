r"""
Урок "Строки и методы строк", шаг 13
https://stepik.org/lesson/2493450/step/13

Напишите программу, которая считывает строку из слов, разделённых запятыми, и выводит эти слова
через пробел.
🔑 Подсказка
Сначала разбейте строку по запятой методом `.split(",")`, получится список слов. Затем соедините их
через пробел методом `" ".join()`.
"""

s = input()
print(" ".join(s.split(",")))
