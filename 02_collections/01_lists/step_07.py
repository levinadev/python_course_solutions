r"""
Урок "Списки", шаг 7
https://stepik.org/lesson/2493454/step/7

Напишите программу, которая считывает рост учеников класса в сантиметрах (различные целые числа
через пробел), а во второй строке рост Пети (он есть среди этих чисел).
Ученики строятся по росту, от самого высокого к самому низкому. Отсортируйте список методом
`.sort()` с параметром `reverse=True`, найдите позицию Пети методом `.index()` и выведите, каким по
счёту он стоит в строю (нумерация с 1).
🔑 Подсказка
После `heights.sort(reverse=True)` метод `.index()` вернёт позицию Пети, считая с нуля. Чтобы
получить номер в строю, прибавьте 1.
"""

heights = [int(x) for x in input().split()]
petya = int(input())
heights.sort(reverse=True)
print(heights.index(petya) + 1)
