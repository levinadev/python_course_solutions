r"""
Урок "Списки", шаг 8
https://stepik.org/lesson/2493454/step/8

На вход подаётся строка, в ней оценки от 1 до 5 через пробел (среди них есть хотя бы одна двойка).
Создайте из них список и выполните по порядку четыре действия.
- Добавьте в конец списка оценку `5`.
- Удалите из списка оценку `2` (первое вхождение).
- Вставьте оценку `4` на позицию с индексом `1`.
- Отсортируйте список по убыванию.
Выведите полученный список.
🔑 Подсказка
Выполняйте действия строго по порядку, от него зависит результат. Методы вызывайте прямо у списка,
например `grades.append(5)`.
"""

grades = [int(x) for x in input().split()]
grades.append(5)
grades.remove(2)
grades.insert(1, 4)
grades.sort(reverse=True)
print(grades)
