r"""
Урок "Итоговый проект", шаг 1
https://stepik.org/lesson/2493464/step/1

Система учёта оценок
Условие
Напишите программу, которая работает со списком оценок студентов.
Что должна делать программа.
- Хранить список оценок (целые числа от 1 до 5).
- Выводить среднюю оценку.
- Выводить количество пятёрок.
- Выводить количество двоек.
Требования
- Используйте список для хранения оценок.
- Вычисления выполняются в цикле.
Ввод
На вход подаётся список оценок через пробел, например `5 4 3 5 4 2`.
Вывод
Три числа на отдельных строках.
- Средняя оценка, например `3.8333333333333335`.
- Количество пятёрок.
- Количество двоек.
🔑 Подсказка
- Строку разбейте методом `.split()`, получится список строк вроде `['5', '4', '3']`. Перед
сложением и сравнением превращайте каждую оценку в число через `int()`.
- До цикла заведите `total = 0` для суммы и два счётчика для пятёрок и двоек. В цикле прибавляйте
оценку к `total` и увеличивайте на 1 нужный счётчик.
- Среднее равно сумме, делённой на количество оценок, а количество даёт `len()`.
"""

grades = [int(x) for x in input().split()]
total = 0
fives = 0
twos = 0
for g in grades:
    total += g
    if g == 5:
        fives += 1
    if g == 2:
        twos += 1
print(total / len(grades))
print(fives)
print(twos)
