r"""
Урок "Словари", шаг 7
https://stepik.org/lesson/2493458/step/7

На вход подаётся строка, в ней пары `ключ=значение` через пробел (ключи не повторяются). Создайте из
них словарь `student` (значения в виде строк).
Используя метод `.values()`, выведите все значения словаря, каждое на отдельной строке.
🔑 Подсказка
Строку разбейте по пробелам, а каждую пару ещё раз по знаку равенства, `pair.split("=")`. Первая
часть станет ключом, вторая значением. Значения выведите циклом по `student.values()`.
"""

student = {}
for pair in input().split():
    key, value = pair.split("=")
    student[key] = value
for value in student.values():
    print(value)
