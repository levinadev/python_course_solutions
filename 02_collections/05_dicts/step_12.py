r"""
Урок "Словари", шаг 12
https://stepik.org/lesson/2493458/step/12

Считайте имя, возраст (целое число) и телефон, каждое с новой строки. Создайте словарь `user =
{"name": имя, "email": "user@mail.ru", "age": возраст}` и выполните пять действий.
- Используя `.setdefault()`, добавьте ключ `"city"` со значением `"Санкт-Петербург"` (если его нет).
- Используя `.update()`, добавьте пару `"phone"` со считанным телефоном.
- Используя `.pop()`, удалите ключ `"age"` и сохраните его значение в переменную `age`.
- Используя `.get()`, получите значение ключа `"name"` и сохраните в переменную `name`.
- Выведите строку `Имя: {name}, Возраст: {age}, Город: {city}, Телефон: {phone}`, а на следующей
строке итоговый словарь.
🔑 Подсказка
Возраст переведите через `int()`. Метод `.pop("age")` возвращает удалённое значение, сохраните его в
`age`. Город и телефон для строки вывода возьмите из словаря по ключам.
"""

name_in = input()
age_in = int(input())
phone_in = input()
user = {"name": name_in, "email": "user@mail.ru", "age": age_in}
user.setdefault("city", "Санкт-Петербург")
user.update({"phone": phone_in})
age = user.pop("age")
name = user.get("name")
print(f"Имя: {name}, Возраст: {age}, Город: {user['city']}, Телефон: {user['phone']}")
print(user)
