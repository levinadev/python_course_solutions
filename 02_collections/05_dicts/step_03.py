r"""
Урок "Словари", шаг 3
https://stepik.org/lesson/2493458/step/3

Дан словарь `book = {"title": "Война и мир", "author": "Толстой", "year": 1867}`. Книгу переиздали.
Программа считывает год переиздания и количество страниц (каждое с новой строки). Запишите год в
ключ `"year"`, добавьте новый ключ `"pages"` со считанным числом страниц и выведите словарь.
🔑 Подсказка
Запись `book["year"] = int(input())` меняет значение ключа, который уже есть, а такая же запись с
новым ключом `"pages"` добавляет его.
"""

book = {"title": "Война и мир", "author": "Толстой", "year": 1867}
book["year"] = int(input())
book["pages"] = int(input())
print(book)
