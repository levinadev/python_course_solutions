r"""
Урок "Словари", шаг 6
https://stepik.org/lesson/2493458/step/6

Программа считывает меню кафе. В первой строке количество блюд `n`, далее `n` строк вида `блюдо
цена` (название из одного слова, цена целым числом). Сохраните меню в словарь `menu`, где ключом
служит блюдо, а значением цена.
Используя метод `.keys()`, выведите названия всех блюд, каждое на отдельной строке.
🔑 Подсказка
Начните с пустого словаря `menu = {}`. В цикле по n строкам разбейте строку через `.split()`,
название `parts[0]` станет ключом, а `int(parts[1])` значением. Потом пройдите циклом по
`menu.keys()`.
"""

menu = {}
for _ in range(int(input())):
    dish, price = input().split()
    menu[dish] = int(price)
for dish in menu.keys():
    print(dish)
