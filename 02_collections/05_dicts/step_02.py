r"""
Урок "Словари", шаг 2
https://stepik.org/lesson/2493458/step/2

Напишите программу, которая считывает название фильма, год выхода и режиссёра, каждое с новой
строки, и сохраняет их в словарь `movie` с ключами `"title"`, `"year"` (целое число) и `"director"`.
Выведите строку `{title} ({year}), режиссёр {director}`, получая значения из словаря по ключам.
🔑 Подсказка
Год переведите через `int()`. Значения достаньте по ключам в переменные, например `title =
movie["title"]`, и подставьте их в f-строку.
"""

movie = {"title": input(), "year": int(input()), "director": input()}
print(f"{movie['title']} ({movie['year']}), режиссёр {movie['director']}")
