r"""
Урок "Словари", шаг 10
https://stepik.org/lesson/2493458/step/10

Дан словарь `product = {"title": "Ноутбук", "price": 75000, "brand": "Asus"}`. Считайте два ключа
(каждый с новой строки).
Используя метод `.get()` со значением по умолчанию `0`, получите значения обоих ключей и выведите их
в формате `Первое: {значение1}, Второе: {значение2}`.
🔑 Подсказка
`product.get(key, 0)` вернёт значение ключа, а если такого ключа нет, вернёт 0. Ключи считайте через
`input()`.
"""

product = {"title": "Ноутбук", "price": 75000, "brand": "Asus"}
first = product.get(input(), 0)
second = product.get(input(), 0)
print(f"Первое: {first}, Второе: {second}")
