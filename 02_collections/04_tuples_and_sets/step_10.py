r"""
Урок "Кортежи и множества", шаг 10
https://stepik.org/lesson/2493457/step/10

Напишите программу, которая считывает города, в которых турист побывал за лето, через пробел (в
некоторые города он ездил несколько раз).
С помощью множества уберите повторы, отсортируйте города функцией `sorted()` и выведите получившийся
список.
🔑 Подсказка
Множество `set()` оставит каждый город один раз, а `sorted()` вернёт из него отсортированный список.
"""

cities = set(input().split())
print(sorted(cities))
