r"""
Урок "Кортежи и множества", шаг 6
https://stepik.org/lesson/2493457/step/6

Даны три строки. В первой и второй целые числа через пробел, в третьей натуральное число `k`.
Создайте из первых двух строк кортежи `a` и `b`.
Выведите на двух строках результат сложения кортежей (`a + b`) и результат умножения кортежа `a` на
`k` (`a * k`).
🔑 Подсказка
Кортежи склеиваются через `+`, а `a * k` повторяет кортеж k раз. Числа и k переведите через `int()`.
"""

a = tuple([int(x) for x in input().split()])
b = tuple([int(x) for x in input().split()])
k = int(input())
print(a + b)
print(a * k)
