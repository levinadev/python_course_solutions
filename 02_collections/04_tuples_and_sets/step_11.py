r"""
Урок "Кортежи и множества", шаг 11
https://stepik.org/lesson/2493457/step/11

В школе работают два кружка. Программа считывает две строки. В первой имена участников шахматного
кружка, во второй участников кружка робототехники (через пробел).
Создайте из них множества и выведите на двух строках отсортированными списками всех, кто ходит хотя
бы в один кружок (`|`), и тех, кто ходит в оба кружка (`&`).
🔑 Подсказка
Создайте множества `chess` и `robots` через `set()`. Объединение даёт `chess | robots`, пересечение
`chess & robots`, каждое оберните в `sorted()`.
"""

chess = set(input().split())
robots = set(input().split())
print(sorted(chess | robots))
print(sorted(chess & robots))
