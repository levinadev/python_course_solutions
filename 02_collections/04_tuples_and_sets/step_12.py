r"""
Урок "Кортежи и множества", шаг 12
https://stepik.org/lesson/2493457/step/12

В первой строке названия цветов через пробел, во второй цвет, который нужно добавить, в третьей
цвет, который нужно удалить (он точно есть в первой строке). Создайте из первой строки множество
`colors`.
Добавьте цвет методом `.add()`, удалите цвет методом `.remove()` и выведите отсортированный список
полученных элементов.
🔑 Подсказка
Сначала `colors.add(new)`, затем `colors.remove(old)`, а выведите `sorted(colors)`.
"""

colors = set(input().split())
new = input()
old = input()
colors.add(new)
colors.remove(old)
print(sorted(colors))
