r"""
Урок "Кортежи и множества", шаг 8
https://stepik.org/lesson/2493457/step/8

В первой строке названия животных через пробел, во второй ещё одно название. Создайте из первой
строки множество `animals`.
Проверьте, есть ли в нём второе название, и выведите `True` или `False`. Используйте оператор `in`.
🔑 Подсказка
Множество из строки даёт `set(input().split())`. Выражение `name in animals` само даёт `True` или
`False`.
"""

animals = set(input().split())
print(input() in animals)
