r"""
Урок "Кортежи и множества", шаг 5
https://stepik.org/lesson/2493457/step/5

В первой строке целые числа через пробел, во второй число `x`, которое точно есть среди них.
Создайте из первой строки кортеж `data`.
Выведите на двух строках количество вхождений числа `x` (метод `.count()`) и индекс первого
вхождения `x` (метод `.index()`).
🔑 Подсказка
Кортеж чисел получите через `tuple()` от списка чисел. Число x тоже переведите через `int()`, иначе
`.count()` и `.index()` не найдут его среди чисел.
"""

data = tuple([int(x) for x in input().split()])
x = int(input())
print(data.count(x))
print(data.index(x))
