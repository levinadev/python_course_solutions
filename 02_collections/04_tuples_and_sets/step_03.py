r"""
Урок "Кортежи и множества", шаг 3
https://stepik.org/lesson/2493457/step/3

Напишите программу, которая считывает координаты точки в пространстве, три целых числа через пробел,
и сохраняет их в список.
Координаты точки не должны меняться, поэтому преобразуйте список в кортеж `point`. Выведите кортеж,
а на следующей строке его тип с помощью `type()`.
🔑 Подсказка
Список чисел соберите через `[int(x) for x in input().split()]`, затем `point = tuple(coords)`. Во
второй строке выведите `type(point)`.
"""

coords = [int(x) for x in input().split()]
point = tuple(coords)
print(point)
print(type(point))
