r"""
Урок "Работа со списками продвинутая", шаг 10
https://stepik.org/lesson/2493456/step/10

Дан вложенный список, матрица. Вычислите сумму всех элементов матрицы и выведите её.
Ввод. Сначала число строк таблицы, затем сами строки, в каждой целые числа через пробел. Прочитать
такую таблицу можно двумя строками кода `rows = int(input())` и `table = [list(map(int,
input().split())) for _ in range(rows)]`
🔑 Подсказка
Нужны два вложенных цикла, по строкам и по числам в строке. До циклов заведите `total = 0` и
прибавляйте к нему каждое число.
"""

matrix = [[int(x) for x in input().split()] for _ in range(int(input()))]
total = 0
for row in matrix:
    for x in row:
        total += x
print(total)
