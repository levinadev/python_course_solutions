r"""
Урок "Работа со списками продвинутая", шаг 13
https://stepik.org/lesson/2493456/step/13

На вход подаётся строка, в ней элементы через пробел (не меньше одного). Создайте из неё список
`original`.
Создайте его копию через метод `.copy()`, удалите из копии последний элемент с помощью `.pop()` и
выведите копию, а на следующей строке оригинал.
🔑 Подсказка
Сделайте `copy = original.copy()`, затем `copy.pop()` без аргумента удалит последний элемент.
Выведите сначала копию, потом оригинал.
"""

original = input().split()
copy = original.copy()
copy.pop()
print(copy)
print(original)
