r"""
Урок "Работа со списками продвинутая", шаг 5
https://stepik.org/lesson/2493456/step/5

Считайте два целых числа `a` и `b` (каждое с новой строки, `a <= b`).
С помощью цикла `for` и функции `range()` выведите все числа от `a` до `b` включительно, каждое на
отдельной строке.
🔑 Подсказка
`range(start, stop)` идёт от `start`, но само `stop` не включает, это разбиралось в уроке 3.2
"Циклы". Чтобы `b` попало в вывод, верхнюю границу сделайте `b + 1`.
"""

a = int(input())
b = int(input())
for i in range(a, b + 1):
    print(i)
