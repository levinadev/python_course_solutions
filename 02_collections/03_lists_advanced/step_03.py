r"""
Урок "Работа со списками продвинутая", шаг 3
https://stepik.org/lesson/2493456/step/3

На вход подаётся строка, в ней целые числа через пробел. Создайте из них список `numbers`, вычислите
сумму всех элементов и выведите её.
Для этого используйте переменную, в которой будет постепенно накапливаться сумма.
🔑 Подсказка
До цикла заведите `total = 0`, в цикле `for x in numbers` прибавляйте каждый элемент, а сумму
выведите после цикла.
"""

numbers = [int(x) for x in input().split()]
total = 0
for x in numbers:
    total += x
print(total)
