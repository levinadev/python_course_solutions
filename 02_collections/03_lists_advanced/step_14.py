r"""
Урок "Работа со списками продвинутая", шаг 14
https://stepik.org/lesson/2493456/step/14

В первой строке целые числа через пробел, во второй число `x`. Создайте из первой строки список
`original`. Напишите программу, которая делает четыре шага.
- Создаёт копию списка (любым способом).
- Изменяет копию, добавляет в неё число `x`.
- Выводит оригинал, на следующей строке копию.
- Выводит `Оригинал не изменился`, если оригинал остался прежним, иначе `Оригинал изменился`.
🔑 Подсказка
Копию сделайте через `original.copy()` или срез `[:]`. Чтобы проверить оригинал, запомните его длину
через `len()` до изменений и в конце сравните с ней.
"""

original = [int(x) for x in input().split()]
x = int(input())
saved = list(original)
copy = original.copy()
copy.append(x)
print(original)
print(copy)
if original == saved:
    print("Оригинал не изменился")
else:
    print("Оригинал изменился")
