r"""
Урок "Работа со списками продвинутая", шаг 9
https://stepik.org/lesson/2493456/step/9

Дана таблица результатов олимпиады, каждая строка содержит баллы одного участника за туры. Выведите
баллы всех участников за первый тур (столбец с индексом 0), каждое число на отдельной строке.
Ввод. Сначала число строк таблицы, затем сами строки, в каждой целые числа через пробел. Прочитать
такую таблицу можно двумя строками кода `rows = int(input())` и `table = [list(map(int,
input().split())) for _ in range(rows)]`
🔑 Подсказка
Переберите строки таблицы циклом `for row in table` и выводите у каждой `row[0]`.
"""

matrix = [[int(x) for x in input().split()] for _ in range(int(input()))]
for row in matrix:
    print(row[0])
