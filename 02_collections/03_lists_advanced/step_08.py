r"""
Урок "Работа со списками продвинутая", шаг 8
https://stepik.org/lesson/2493456/step/8

Дан вложенный список, матрица. После неё в отдельной строке через пробел даны два числа, индекс
строки `i` и индекс столбца `j`.
Выведите элемент, который находится в строке с индексом `i` и столбце с индексом `j`.
Ввод. Сначала число строк таблицы, затем сами строки, в каждой целые числа через пробел. Прочитать
такую таблицу можно двумя строками кода `rows = int(input())` и `table = [list(map(int,
input().split())) for _ in range(rows)]` После таблицы идёт строка с индексами `i j`.
🔑 Подсказка
Таблицу прочитайте двумя строками кода из условия. Строку с индексами разбейте через `.split()` и
переведите оба индекса в числа, а элемент возьмите двойной индексацией `table[i][j]`.
"""

matrix = [[int(x) for x in input().split()] for _ in range(int(input()))]
i, j = map(int, input().split())
print(matrix[i][j])
