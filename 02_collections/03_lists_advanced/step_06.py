r"""
Урок "Работа со списками продвинутая", шаг 6
https://stepik.org/lesson/2493456/step/6

На чётной стороне улицы дома имеют чётные номера. Напишите программу, которая считывает номера
первого и последнего дома участка `a` и `b` (каждое с новой строки; оба чётные, `a <= b`).
С помощью цикла `for` и функции `range()` с шагом выведите номера всех домов участка от `a` до `b`
включительно, каждый на отдельной строке.
🔑 Подсказка
`range(start, stop, step)` идёт с шагом `step`. Чётные номера идут через один, поэтому шаг 2, а
верхняя граница `b + 1`, чтобы последний дом попал в вывод.
"""

a = int(input())
b = int(input())
for house in range(a, b + 1, 2):
    print(house)
