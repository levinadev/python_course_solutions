r"""
Урок "Работа со списками продвинутая", шаг 2
https://stepik.org/lesson/2493456/step/2

Напишите программу, которая считывает список дел, дела через точку с запятой (например, `купить
хлеб;позвонить маме;сделать уроки`).
Сохраните дела в список и с помощью цикла `for` выведите каждое дело на отдельной строке в формате
`- {дело}`.
🔑 Подсказка
Разделитель передайте в метод, `input().split(";")`. Тогда дела с пробелами внутри, например "купить
хлеб", останутся целыми. В цикле выводите каждое дело f-строкой `f"- {task}"`.
"""

tasks = input().split(";")
for task in tasks:
    print(f"- {task}")
