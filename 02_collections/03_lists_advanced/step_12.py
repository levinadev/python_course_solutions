r"""
Урок "Работа со списками продвинутая", шаг 12
https://stepik.org/lesson/2493456/step/12

В первой строке целые числа через пробел, во второй число `x`. Создайте из первой строки список
`original`.
Создайте его копию через срез `[:]`, добавьте в копию число `x`, затем выведите оригинальный список,
а на следующей строке копию.
🔑 Подсказка
Срез `original[:]` создаёт новый список, поэтому `append()` в копии не меняет оригинал.
"""

original = [int(x) for x in input().split()]
x = int(input())
copy = original[:]
copy.append(x)
print(original)
print(copy)
