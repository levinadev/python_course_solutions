r"""
Урок "Циклы", шаг 10
https://stepik.org/lesson/2493455/step/10

Напишите программу, которая считывает целое число `n`.
С помощью вложенных циклов выведите таблицу умножения для всех чисел от `1` до `n`.
Выводите каждую строку в таком формате.
```
i * j = результат
```
🔑 Подсказка
- Чтобы цикл прошёл от `1` до `n` включительно, вспомните, что верхняя граница `range()` не входит в
диапазон.
- Внешний цикл перебирает `i`, внутренний `j`, а строку удобно вывести f-строкой `f"{i} * {j} = {i *
j}"`.
"""

n = int(input())
for i in range(1, n + 1):
    for j in range(1, n + 1):
        print(f"{i} * {j} = {i * j}")
