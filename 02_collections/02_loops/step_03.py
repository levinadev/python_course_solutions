r"""
Урок "Циклы", шаг 3
https://stepik.org/lesson/2493455/step/3

Напишите программу, которая считывает целое число `n` и выводит все чётные числа от 0
до `n` включительно (каждое на отдельной строке).
🔑 Подсказка
Третий аргумент `range()` задаёт шаг. `range(0, n + 1, 2)` даёт 0, 2, 4 и так далее до n
включительно.
"""

n = int(input())
for i in range(0, n + 1, 2):
    print(i)
