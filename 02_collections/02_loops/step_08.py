r"""
Урок "Циклы", шаг 8
https://stepik.org/lesson/2493455/step/8

Напишите программу, которая сначала считывает целое число `n`, количество чисел.
Затем программа должна считать ещё `n` целых чисел.
Выведите только нечётные числа, каждое с новой строки.
🔑 Подсказка
Числа считывайте внутри цикла `for i in range(n)`, по одному `int(input())` за проход. У нечётного
числа остаток от деления на 2 не равен нулю, `x % 2 != 0`.
"""

n = int(input())
for _ in range(n):
    x = int(input())
    if x % 2 != 0:
        print(x)
