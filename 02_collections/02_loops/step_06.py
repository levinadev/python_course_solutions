r"""
Урок "Циклы", шаг 6
https://stepik.org/lesson/2493455/step/6

Напишите программу, которая загадывает число `5`. Программа считывает числа, пока пользователь не
угадает число `5`.
Как только число угадано, программа выводит `Угадал! Попыток: N`, где `N` означает, сколько чисел
было введено, включая угаданное, и завершается.
🔑 Подсказка
Первое число считайте до цикла и сразу посчитайте его попыткой. Цикл `while n != 5` считывает
следующее число и увеличивает счётчик на 1. После цикла выведите сообщение f-строкой.
"""

attempts = 0
while True:
    attempts += 1
    if int(input()) == 5:
        print(f"Угадал! Попыток: {attempts}")
        break
