r"""
Урок "Циклы", шаг 5
https://stepik.org/lesson/2493455/step/5

Напишите программу, которая считывает числа и суммирует их.
Программа должна завершиться, когда пользователь введёт `0`.
Выведите сумму всех введённых чисел (не считая `0`).
🔑 Подсказка
Считайте первое число до цикла. Цикл `while n != 0` прибавляет число к сумме и считывает следующее.
Сумму выведите после цикла.
"""

total = 0
while True:
    n = int(input())
    if n == 0:
        break
    total += n
print(total)
