r"""
Урок "Циклы", шаг 2
https://stepik.org/lesson/2493455/step/2

Напишите программу, которая считывает целое число `n` и выводит сумму всех чисел от 1
до `n` включительно.
🔑 Подсказка
До цикла заведите `total = 0`. Цикл `for i in range(1, n + 1)` пройдёт от 1 до n включительно, на
каждом шаге прибавляйте `i` к `total`. Сумму выведите после цикла.
"""

n = int(input())
total = 0
for i in range(1, n + 1):
    total += i
print(total)
